"""Fixture workspace for the diagram generator (plan decisions D17, D28).

The fixture is fictional. Two small patterns cover every D17 feature; the
large pattern is generated by make_large.py and must regenerate byte for byte.
"""

from __future__ import annotations

import re
import subprocess
import sys
import tempfile
import unittest
from collections import Counter
from pathlib import Path
from typing import Any

import yaml

from framework.tools import generate_diagram
from uid_utils import UID_PATTERN_TEXT

REPO_ROOT = Path(__file__).resolve().parents[1]
FIXTURE = REPO_ROOT / "tests" / "fixtures" / "diagram_workspace"
MAKE_LARGE = FIXTURE / "make_large.py"
COMMITTED_LARGE = FIXTURE / "catalog" / "large-pattern.yaml"
SMALL_SDPS = ("FXSDP00001-0001", "FXSDP00002-0001")
UID_PATTERN = re.compile(UID_PATTERN_TEXT)


def _load() -> dict[str, dict[str, Any]]:
    return generate_diagram.load_catalog(FIXTURE)


def _entries(sdp: dict[str, Any]) -> list[tuple[dict[str, Any], dict[str, Any]]]:
    pairs = []
    for group in sdp.get("serviceGroups") or []:
        for entry in group.get("deployableObjects") or []:
            pairs.append((group, entry))
    return pairs


class FixtureLoadTests(unittest.TestCase):
    def test_fixture_loads_three_sdps_with_fx_uids(self) -> None:
        catalog = _load()
        sdps = [o for o in catalog.values() if o.get("type") == "software_deployment_pattern" and not o.get("_derived")]
        self.assertEqual(3, len(sdps))
        authored = [o for o in catalog.values() if not o.get("_derived")]
        for obj in authored:
            with self.subTest(uid=obj.get("uid")):
                self.assertTrue(str(obj["uid"]).startswith("FX"))
                self.assertRegex(str(obj["uid"]), UID_PATTERN)

    def test_no_uid_is_declared_twice_across_fixture_files(self) -> None:
        declared: Counter[str] = Counter()
        for path in sorted((FIXTURE / "catalog").glob("*.yaml")):
            for doc in yaml.safe_load_all(path.read_text(encoding="utf-8")):
                if isinstance(doc, dict) and doc.get("uid"):
                    declared[str(doc["uid"])] += 1
        self.assertEqual([], [uid for uid, n in declared.items() if n > 1])


class FixtureCoverageTests(unittest.TestCase):
    """One assertion per D17 feature, each named after the feature."""

    @classmethod
    def setUpClass(cls) -> None:
        cls.catalog = _load()
        cls.small = [cls.catalog[uid] for uid in SMALL_SDPS]
        cls.placed: dict[str, set[str]] = {}
        cls.placed_in: dict[str, set[str]] = {}
        for sdp in cls.small:
            uids = {entry["ref"] for _, entry in _entries(sdp)}
            cls.placed[sdp["uid"]] = uids
            for uid in uids:
                cls.placed_in.setdefault(uid, set()).add(sdp["uid"])
        cls.rels = [
            o for o in cls.catalog.values()
            if o.get("type") == "relationship" and not o.get("_derived") and str(o["uid"]).startswith("FXEDG")
        ]
        cls.groups = [g for sdp in cls.small for g in sdp.get("serviceGroups") or []]

    def test_d17_two_deployment_targets(self) -> None:
        targets = {g.get("deploymentTarget") for g in self.groups}
        self.assertGreaterEqual(len(targets), 2)

    def test_d17_group_spanning_two_zones(self) -> None:
        self.assertTrue(any(
            len({e.get("networkZone") for _, e in _entries({"serviceGroups": [g]}) if e.get("networkZone")}) >= 2
            for g in self.groups
        ))

    def test_d17_substrate_disagrees_with_runs_on(self) -> None:
        found = False
        for g in self.groups:
            substrate = g.get("substrate")
            for _, entry in _entries({"serviceGroups": [g]}):
                obj = self.catalog.get(entry["ref"], {})
                if substrate and obj.get("runsOn") and obj["runsOn"] != substrate:
                    found = True
        self.assertTrue(found)

    def test_d17_external_target_relationship(self) -> None:
        self.assertTrue(any(r.get("externalTarget") for r in self.rels))

    def test_d17_endpoint_placed_in_other_sdp(self) -> None:
        found = False
        for rel in self.rels:
            ends = [rel.get("source"), rel.get("target")]
            homes = [self.placed_in.get(e, set()) for e in ends if e]
            if any(len(h) == 1 for h in homes) and len(set().union(*homes)) >= 2:
                found = True
        self.assertTrue(found)

    def test_d17_endpoint_placed_in_no_sdp(self) -> None:
        found = any(
            e and e in self.catalog and not self.placed_in.get(e)
            for r in self.rels
            for e in (r.get("source"), r.get("target"))
        )
        self.assertTrue(found)

    def test_d17_entry_with_no_diagram_tier(self) -> None:
        self.assertTrue(any("diagramTier" not in e for sdp in self.small for _, e in _entries(sdp)))

    def test_d17_uid_placed_twice(self) -> None:
        refs = Counter(e["ref"] for sdp in self.small for _, e in _entries(sdp))
        self.assertTrue(any(n > 1 for n in refs.values()))

    def test_d17_self_relationship(self) -> None:
        self.assertTrue(any(r.get("source") == r.get("target") for r in self.rels))

    def test_d17_retired_object(self) -> None:
        self.assertTrue(any(
            self.catalog[uid].get("lifecycleStatus") == "retired" for uid in self.placed_in if uid in self.catalog
        ))

    def test_d17_synchronous_edge(self) -> None:
        self.assertTrue(any(r.get("direction") == "synchronous" for r in self.rels))

    def test_d17_asynchronous_edge(self) -> None:
        self.assertTrue(any(r.get("direction") == "asynchronous" for r in self.rels))

    def test_d17_event_edge(self) -> None:
        self.assertTrue(any(r.get("direction") == "event" for r in self.rels))

    def test_d17_bidirectional_flow(self) -> None:
        self.assertTrue(any(r.get("flow") == "bidirectional" for r in self.rels))

    def test_d17_group_with_no_drawable_objects(self) -> None:
        self.assertTrue(any(not g.get("deployableObjects") for g in self.groups))

    def test_d17_entry_with_no_network_zone(self) -> None:
        self.assertTrue(any("networkZone" not in e for sdp in self.small for _, e in _entries(sdp)))

    def test_d17_substrate_also_listed_as_deployable_object(self) -> None:
        self.assertTrue(any(
            g.get("substrate") and any(e["ref"] == g["substrate"] for _, e in _entries({"serviceGroups": [g]}))
            for g in self.groups
        ))

    def test_d17_runtime_spec_dependency(self) -> None:
        self.assertTrue(any(
            (o.get("runtimeSpec") or {}).get("dependencies")
            for o in self.catalog.values()
            if str(o.get("uid", "")).startswith("FXPRD") and not o.get("_derived")
        ))

    def test_d17_inbound_flow(self) -> None:
        self.assertTrue(any(r.get("flow") == "inbound" for r in self.rels))


class LargeFixtureTests(unittest.TestCase):
    def _run_make_large(self, out_dir: Path) -> bytes:
        subprocess.run([sys.executable, str(MAKE_LARGE), str(out_dir)], check=True, cwd=out_dir)
        return (out_dir / "large-pattern.yaml").read_bytes()

    def test_make_large_is_reproducible(self) -> None:
        with tempfile.TemporaryDirectory() as first, tempfile.TemporaryDirectory() as second:
            one = self._run_make_large(Path(first))
            two = self._run_make_large(Path(second))
        self.assertEqual(one, two)
        self.assertEqual(COMMITTED_LARGE.read_bytes(), one)

    def test_large_pattern_meets_size_floor(self) -> None:
        docs = [d for d in yaml.safe_load_all(COMMITTED_LARGE.read_text(encoding="utf-8")) if isinstance(d, dict)]
        sdp = next(d for d in docs if d.get("type") == "software_deployment_pattern")
        groups = sdp["serviceGroups"]
        self.assertGreaterEqual(len(groups), 10)
        self.assertGreaterEqual(len({g["deploymentTarget"] for g in groups}), 3)
        placed = [e for g in groups for e in g["deployableObjects"]]
        self.assertGreaterEqual(len(placed), 60)
        rels = [d for d in docs if d.get("type") == "relationship"]
        self.assertGreaterEqual(len(rels), 100)


if __name__ == "__main__":
    unittest.main()
